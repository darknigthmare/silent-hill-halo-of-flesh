/** Compile the reviewed Excel research into a deterministic runtime catalogue.
 * The research remains the source of truth; this module must not import data.js.
 */
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';

const root = new URL('../', import.meta.url);
const inputs = ['classic', 'extended'];
const parts = await Promise.all(inputs.map(async name => JSON.parse(await fs.readFile(new URL(`docs/production/research/${name}.json`, root), 'utf8'))));
const catalogues = {fighters: new Map(), stages: new Map(), sources: new Map()};
for (const part of parts) {
  for (const [kind, catalogue] of Object.entries(catalogues)) {
    if (!Array.isArray(part[kind])) throw new Error(`Missing research array: ${kind}`);
    for (const entry of part[kind]) {
      if (!entry.id || typeof entry.id !== 'string') throw new Error(`Missing ${kind} identity`);
      if (catalogue.has(entry.id)) {
        if (kind !== 'sources' || catalogue.get(entry.id).url !== entry.url) throw new Error(`Conflicting ${kind} identity: ${entry.id}`);
        continue;
      }
      // Search-session handles have no meaning in the shipped application.
      const {webRef, wordLimit, ...value} = entry;
      catalogue.set(entry.id, value);
    }
  }
}
for (const source of catalogues.sources.values()) {
  const url = new URL(source.url);
  if (url.protocol !== 'https:') throw new Error(`Non-HTTPS research source: ${source.id}`);
}
function checkReferences(value, label) {
  if (!value || typeof value !== 'object') return;
  for (const [key, child] of Object.entries(value)) {
    if (['referenceIds', 'evidence', 'basis'].includes(key) && Array.isArray(child)) {
      for (const id of child) if (!catalogues.sources.has(id)) throw new Error(`Unknown source ${id} in ${label}`);
    } else if (child && typeof child === 'object') checkReferences(child, label);
  }
}
for (const kind of ['fighters', 'stages']) for (const entry of catalogues[kind].values()) checkReferences(entry, entry.id);
const serialise = map => Object.fromEntries([...map.entries()].sort(([a], [b]) => a.localeCompare(b, 'en')));
const content = {
  fighters: serialise(catalogues.fighters),
  stages: serialise(catalogues.stages),
  sources: serialise(catalogues.sources)
};
const digest = createHash('sha256').update(JSON.stringify(content)).digest('hex');
const code = `// Generated by scripts/build-production-reference.mjs. Edit docs/production/research/*.json instead.\n`
  + `// Descriptions distinguish documented observations, proposals and unverified identities.\n`
  + `export const PRODUCTION_REFERENCE_REVISION = ${JSON.stringify(digest)};\n`
  + `export const FIGHTER_REFERENCES = Object.freeze(${JSON.stringify(content.fighters, null, 2)});\n`
  + `export const STAGE_REFERENCES = Object.freeze(${JSON.stringify(content.stages, null, 2)});\n`
  + `export const REFERENCE_SOURCES = Object.freeze(${JSON.stringify(content.sources, null, 2)});\n`;
const target = new URL('src/production-reference.js', root);
const indexTarget = new URL('data/production-reference-index.json', root);
const index = JSON.stringify({schema:1, revision:digest, fighters:Object.fromEntries(Object.values(content.fighters).map(f=>[f.id,f.source])), stages:Object.fromEntries(Object.values(content.stages).map(s=>[s.id,s.source]))},null,2)+'\n';
if (process.argv.includes('--check')) {
  if (await fs.readFile(target, 'utf8') !== code) throw new Error('Production reference is stale; run node scripts/build-production-reference.mjs.');
  if (await fs.readFile(indexTarget, 'utf8') !== index) throw new Error('Production reference authoring index is stale.');
} else {
  await fs.mkdir(new URL('data/',root),{recursive:true});
  await fs.writeFile(target, code);
  await fs.writeFile(indexTarget, index);
}
console.log(`Production references: ${catalogues.fighters.size} fighters, ${catalogues.stages.size} stages, ${catalogues.sources.size} sources (${digest.slice(0, 12)}).`);
